// @vitest-environment jsdom
import { afterEach, beforeAll, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { MemoryRouter, Route, Routes } from 'react-router-dom'
import { FarmProvider } from '../farm/FarmProvider'
import PortalApp, { PortalHub } from './PortalApp'
import { moduleLabels, roles } from './config'
import { businessGroups, businessEntryPath } from './businessGroups'

beforeAll(() => {
  Object.defineProperty(HTMLDialogElement.prototype, 'showModal', { configurable: true, value: function () { this.setAttribute('open', '') } })
  Object.defineProperty(HTMLDialogElement.prototype, 'close', { configurable: true, value: function () { this.removeAttribute('open') } })
})
afterEach(() => { cleanup(); vi.restoreAllMocks(); localStorage.clear() })
const setup = (path: string) => render(<MemoryRouter initialEntries={[path]}><FarmProvider><Routes><Route path="/workspace/:role/*" element={<PortalApp/>}/><Route path="/workspaces" element={<PortalHub/>}/></Routes></FarmProvider></MemoryRouter>)
const switchTo = (role: string, module: string) => { const current = roles.find(r => r.id === role)!; fireEvent.click(screen.getByRole('combobox', { name: '切换演示角色' })); fireEvent.click(screen.getByRole('option', { name: current.name })); const entry = businessGroups(current).flatMap(g => g.entries).find(e => e.variants.some(m => moduleLabels[m] === module)); if (!entry) throw new Error(`该身份没有入口：${module}`); fireEvent.click(within(screen.getByRole('navigation', { name: '角色业务导航' })).getByRole('link', { name: entry.title })) }

describe('角色后台页面与交互', () => {
  it.each(roles)('$name工作台可打开且只展示对应菜单', role => {
    setup(`/workspace/${role.id}`)
    expect(screen.getByRole('heading', { name: role.headline })).toBeTruthy()
    const navigation = within(screen.getByRole('navigation', { name: '角色业务导航' }))
    const entries = businessGroups(role).flatMap(g => g.entries)
    expect(navigation.getAllByRole('link')).toHaveLength(entries.length + 1)
    for (const entry of entries) expect(navigation.getByRole('link', { name: entry.title }).getAttribute('href')).toBe(businessEntryPath(role, entry.id))
    expect(entries.flatMap(e => e.variants).sort()).toEqual([...role.modules].sort())
  })
  it.each(roles.flatMap(role => role.modules.map(module => ({ role, module }))))('$role.name / $module业务页可渲染', async ({ role, module }) => {
    setup(`/workspace/${role.id}/${module}`)
    await waitFor(() => expect(document.querySelector('main h1,main h2')).toBeTruthy())
    expect(screen.queryByText('此角色没有该业务入口')).toBeNull()
  })
  it('采购商直达成本或检测页面被阻断，未知角色有返回入口', () => {
    const view = setup('/workspace/buyer/costs')
    expect(screen.getByText('此角色没有该业务入口')).toBeTruthy()
    expect(screen.queryByText('¥41,000.00')).toBeNull()
    view.unmount(); setup('/workspace/unknown')
    expect(screen.getByText('没有这个角色工作台')).toBeTruthy()
  })
  it('农服接单、开始、完工状态联动，但同一账号切换角色仍不能自验收', () => {
    setup('/workspace/team/services')
    fireEvent.click(screen.getByRole('button', { name: '接受订单' }))
    fireEvent.click(screen.getByRole('button', { name: '开始作业' }))
    fireEvent.click(screen.getByRole('button', { name: '提交完工' }))
    fireEvent.change(screen.getByLabelText('作业完成情况'), { target: { value: '按照委托要求完成葡萄修剪' } })
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    expect(screen.queryByRole('button', { name: '确认验收' })).toBeNull()
    switchTo('farmer', '农事服务')
    fireEvent.click(screen.getByRole('button', { name: '确认验收' }))
    expect(screen.getByRole('status').textContent).toContain('独立账号')
    for (const row of screen.getAllByRole('row', { name: /SRV-001/ })) expect(within(row).getByText('待验收')).toBeTruthy()
  })
  it('种植户申请服务会出现在所选农机站队列', () => {
    setup('/workspace/farmer/services')
    fireEvent.click(screen.getByRole('button', { name: '申请服务' }))
    fireEvent.change(screen.getByLabelText('服务方'), { target: { value: 'machine' } })
    fireEvent.change(screen.getByLabelText('作业内容'), { target: { value: '测试果园转运' } })
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    switchTo('machine', '农事服务')
    expect(screen.getByRole('row', { name: /测试果园转运/ })).toBeTruthy()
    expect(screen.queryByRole('row', { name: /SRV-001/ })).toBeNull()
  })
  it('植保补齐档案后才可完工，专业凭据可被对应种植户查看', () => {
    setup('/workspace/protection/services')
    fireEvent.click(screen.getByRole('button', { name: '开始作业' }))
    fireEvent.click(screen.getByRole('button', { name: '提交完工' }))
    fireEvent.change(screen.getByLabelText('作业完成情况'), { target: { value: '模拟植保作业已完成' } })
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    expect(screen.getByRole('alert').textContent).toContain('补齐')
    fireEvent.click(screen.getByRole('button', { name: '关闭窗口' }))
    fireEvent.click(screen.getByRole('link', { name: '植保作业档案' }))
    fireEvent.click(screen.getByRole('button', { name: '登记植保作业' }))
    expect((screen.getByLabelText('标签安全间隔 / 天') as HTMLInputElement).value).toBe('')
    fireEvent.change(screen.getByLabelText('药剂名称（按标签）'), { target: { value: '虚构测试药剂' } })
    fireEvent.change(screen.getByLabelText('药剂生产批次'), { target: { value: 'DEMO-SPRAY' } })
    fireEvent.change(screen.getByLabelText('标签安全间隔 / 天'), { target: { value: '7' } })
    fireEvent.change(screen.getByLabelText('核对与现场说明'), { target: { value: '虚构值用于测试，不作为实际施用建议' } })
    fireEvent.click(screen.getByLabelText('已由专业人员核对标签、适用作物与作业方案'))
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    fireEvent.click(screen.getByRole('link', { name: '农事服务' }))
    fireEvent.click(screen.getByRole('button', { name: '提交完工' }))
    fireEvent.change(screen.getByLabelText('作业完成情况'), { target: { value: '模拟植保作业已完成，凭据已补齐' } })
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    switchTo('farmer', '农事记录')
    expect(screen.getByText(/DEMO-SPRAY/)).toBeTruthy()
    expect(screen.getByText(/模拟植保作业已完成，凭据已补齐/)).toBeTruthy()
  })
  it('子女卡片默认只读，授权后可配置，撤销后隐藏私有记录', () => {
    setup('/workspace/family/cards')
    expect((screen.getByRole('button', { name: '设置A/B/C' }) as HTMLButtonElement).disabled).toBe(true)
    switchTo('farmer', '家庭授权')
    fireEvent.click(screen.getByLabelText('代办A/B/C设置与蓝牙同步'))
    fireEvent.click(screen.getByRole('button', { name: '保存家庭授权' }))
    switchTo('family', '我的农事卡')
    fireEvent.click(screen.getByRole('button', { name: '设置A/B/C' }))
    fireEvent.change(screen.getByLabelText('A键作业'), { target: { value: '采收' } })
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    expect(screen.getByText('v2')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '模拟蓝牙同步' }))
    expect(screen.getAllByText('v2')).toHaveLength(2)
    switchTo('farmer', '家庭授权')
    fireEvent.click(screen.getByLabelText('查看农事记录与绑定卡片'))
    fireEvent.click(screen.getByRole('button', { name: '保存家庭授权' }))
    switchTo('family', '农事记录')
    expect(screen.getByText('家庭授权已撤销')).toBeTruthy()
    expect(screen.queryByText('REC-0001')).toBeNull()
  })
  it('NFC销售只登记购买凭据，并联动到对应种植户的农资记录', () => {
    setup('/workspace/supplier/nfc')
    expect(screen.queryByText('陈建国')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: '模拟NFC识别' }))
    fireEvent.click(screen.getByLabelText('已获得农户对本次交易身份关联的确认'))
    fireEvent.click(screen.getByRole('button', { name: '保存销售凭据' }))
    expect(screen.getByRole('row', { name: /有机肥（示例）/ })).toBeTruthy()
    switchTo('farmer', '农事记录')
    expect(screen.getByRole('row', { name: /有机肥（示例）/ })).toBeTruthy()
    expect(screen.queryByText('陈建国')).toBeNull()
  })
  it('种植户的供货撤回使采购端货源消失，不展示农户成本和卡号', () => {
    setup('/workspace/buyer/maturity')
    expect(screen.queryByText('林春梅')).toBeNull()
    expect(screen.queryByText('XQ-C0001')).toBeNull()
    expect(screen.getByText('14,000')).toBeTruthy()
    switchTo('farmer', '供货意向')
    fireEvent.click(screen.getByRole('button', { name: '撤回供货' }))
    switchTo('buyer', '成熟货源')
    expect(screen.getByText('暂时没有匹配的公开货源')).toBeTruthy()
  })
  it('采购预订联动本库订单，取消释放数量；本库不显示其他冷库批次', () => {
    setup('/workspace/buyer/stock')
    fireEvent.click(within(screen.getByRole('row', { name: /BATCH-001/ })).getByRole('button', { name: '预订库存' }))
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    switchTo('warehouse', '库存与订单')
    expect(screen.queryByRole('row', { name: /BATCH-003/ })).toBeNull()
    expect(screen.getByRole('button', { name: '模拟授权出库' })).toBeTruthy()
    expect(screen.queryByText('¥4.80 / kg')).toBeNull()
    switchTo('buyer', '库存与订单')
    fireEvent.click(screen.getByRole('button', { name: '取消预订' }))
    expect(screen.getByText('已取消')).toBeTruthy()
  })
  it('分拣不平衡不能保存；合法记录保存并刷新恢复', () => {
    const view = setup('/workspace/processor/processing')
    fireEvent.click(screen.getByRole('button', { name: '登记分拣' }))
    fireEvent.change(screen.getByLabelText('B级产出 / kg'), { target: { value: '451' } })
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    expect(screen.getByRole('alert').textContent).toContain('必须等于')
    fireEvent.change(screen.getByLabelText('B级产出 / kg'), { target: { value: '450' } })
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '保存演示数据' }))
    expect(screen.queryByRole('dialog')).toBeNull()
    view.unmount(); setup('/workspace/processor/processing')
    expect(screen.getByText('投入产出平衡')).toBeTruthy()
  })
  it('报告需PDF元数据，提交后仅待核验，没有自核验按钮', () => {
    setup('/workspace/lab/samples')
    fireEvent.click(within(screen.getByRole('row', { name: /SAMPLE-002/ })).getByRole('button', { name: '提交检测报告' }))
    fireEvent.change(screen.getByLabelText('报告PDF（≤10MB，只保存文件名）'), { target: { files: [new File(['demo'], 'report.pdf', { type: 'application/pdf' })] } })
    // jsdom cannot populate a file input's native value; exercise submission after its change handler.
    fireEvent.submit(screen.getByRole('dialog').querySelector('form')!)
    expect(within(screen.getByRole('row', { name: /SAMPLE-002/ })).getByText('待运营核验')).toBeTruthy()
    expect(screen.queryByRole('button', { name: /核验/ })).toBeNull()
  })
  it('菜单点击后收起；损坏缓存可恢复；不可写缓存会提示', () => {
    localStorage.setItem('xiangqiao-role-demo-journal-v1', '{broken')
    const view = setup('/workspace/machine/assets')
    expect(screen.getByRole('alert').textContent).toContain('缓存不可用')
    fireEvent.click(screen.getByRole('button', { name: '打开菜单' }))
    expect(view.container.querySelector('.sidebar.is-open')).toBeTruthy()
    fireEvent.click(screen.getByRole('link', { name: '农事服务' }))
    expect(view.container.querySelector('.sidebar.is-open')).toBeNull()
    fireEvent.click(screen.getByRole('link', { name: '服务资源' }))
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('blocked') })
    fireEvent.change(screen.getByLabelText('果园转运机 · 示例01服务状态'), { target: { value: '作业中' } })
    expect(screen.getByRole('alert').textContent).toContain('当前会话')
  })
})
