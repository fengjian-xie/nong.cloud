// @vitest-environment jsdom
import { afterEach, beforeAll, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import type { ReactNode } from 'react'
import { FarmProvider } from './FarmProvider'
import { CardsPage, RecordsPage } from './RecordPages'
import { CostPage, ProductionPage, SoilPage } from './ProductionPages'
import { InventoryPage, MerchantsPage, ProcurementPage } from './CommercePages'
import { MaturityPage, ResourcesPage } from './MapPages'
import { TracePage } from './TracePages'
import { AppShell } from '../components/AppShell'

vi.mock('../auth/AuthContext', () => ({ useAuth: () => ({ session: { user: { name: '测试运营员', role: '演示角色' } }, logout: vi.fn() }) }))

beforeAll(() => {
  Object.defineProperty(HTMLDialogElement.prototype, 'showModal', { configurable: true, value: function () { this.setAttribute('open', '') } })
  Object.defineProperty(HTMLDialogElement.prototype, 'close', { configurable: true, value: function () { this.removeAttribute('open') } })
})
afterEach(() => { cleanup(); vi.restoreAllMocks(); localStorage.clear() })
const setup = (page: ReactNode, path = '/') => render(<MemoryRouter initialEntries={[path]}><FarmProvider>{page}</FarmProvider></MemoryRouter>)

describe('新增管理页面交互', () => {
  it('移动菜单可打开、关闭，导航后收起，桌面菜单可折叠恢复', () => {
    const view = setup(<AppShell><p>测试页面</p></AppShell>)
    fireEvent.click(screen.getByRole('button', { name: '打开菜单' }))
    expect(view.container.querySelector('.sidebar')?.classList.contains('is-open')).toBe(true)
    expect(within(screen.getByRole('navigation', { name: '主导航' })).getAllByRole('link')).toHaveLength(9)
    fireEvent.click(screen.getByRole('link', { name: '生产与记录' }))
    expect(view.container.querySelector('.sidebar')?.classList.contains('is-open')).toBe(false)
    fireEvent.click(screen.getByRole('button', { name: '收起菜单' }))
    expect(view.container.querySelector('.app-shell')?.classList.contains('sidebar-compact')).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: '展开菜单' }))
    expect(view.container.querySelector('.app-shell')?.classList.contains('sidebar-compact')).toBe(false)
  })
  it('卡片配置待下发，模拟同步后设备版本一致，刷新恢复演示操作', () => {
    const view = setup(<CardsPage/>)
    fireEvent.click(within(screen.getByRole('row', { name: /XQ-C0001/ })).getByRole('button', { name: '管理' }))
    fireEvent.change(screen.getByLabelText('作业A'), { target: { value: '采收' } })
    fireEvent.click(screen.getByRole('button', { name: '发布配置版本' }))
    expect(within(screen.getByRole('row', { name: /XQ-C0001/ })).getByText('平台v2 / 卡v1')).toBeTruthy()
    fireEvent.click(within(screen.getByRole('row', { name: /XQ-C0001/ })).getByRole('button', { name: '模拟同步' }))
    expect(screen.getByText('平台v2 / 卡v2')).toBeTruthy()
    view.unmount(); setup(<CardsPage/>)
    expect(screen.getByText('平台v2 / 卡v2')).toBeTruthy()
  })
  it('卡片搜索空态与激活绑定表单有效', () => {
    setup(<CardsPage/>)
    fireEvent.change(screen.getByLabelText('搜索卡号、农户或代办人'), { target: { value: '不存在' } })
    expect(screen.getByText('没有匹配的数据，请调整筛选条件')).toBeTruthy()
    fireEvent.change(screen.getByLabelText('搜索卡号、农户或代办人'), { target: { value: 'XQ-C0007' } })
    fireEvent.click(screen.getByRole('button', { name: '激活绑定' }))
    fireEvent.change(screen.getByLabelText('农户姓名'), { target: { value: '测试农户' } })
    fireEvent.change(screen.getByLabelText('代办人 / 合作社'), { target: { value: '测试子女' } })
    fireEvent.click(screen.getByRole('checkbox'))
    fireEvent.click(screen.getByRole('button', { name: '保存演示绑定' }))
    expect(screen.getByText('测试农户')).toBeTruthy()
  })
  it('记录核验要求说明，离线记录禁止直接通过', () => {
    setup(<RecordsPage/>, '/records?status=待核验')
    fireEvent.click(within(screen.getByRole('row', { name: /REC-0002/ })).getByRole('button', { name: '核验记录' }))
    expect((screen.getByRole('button', { name: '核验通过' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: '关闭窗口' }))
    fireEvent.click(within(screen.getByRole('row', { name: /REC-0001/ })).getByRole('button', { name: '核验记录' }))
    fireEvent.click(screen.getByRole('button', { name: '核验通过' }))
    expect(screen.getByRole('alert').textContent).toContain('至少5个字')
    fireEvent.change(screen.getByLabelText('核验依据 / 纠偏原因'), { target: { value: '现场确认已经完成农事作业' } })
    fireEvent.click(screen.getByRole('button', { name: '核验通过' }))
    expect(screen.queryByRole('row', { name: /REC-0001/ })).toBeNull()
  })
  it('成本计算实时更新，零产量提示错误，保存后可恢复', () => {
    setup(<CostPage/>)
    expect(screen.getByText('¥4.05')).toBeTruthy()
    fireEvent.change(screen.getByLabelText('可售净产量'), { target: { value: '0' } })
    expect(screen.getByRole('alert').textContent).toContain('须大于0')
    fireEvent.change(screen.getByLabelText('可售净产量'), { target: { value: '12000' } })
    expect(screen.getByText('¥5.40')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '保存测算' }))
    fireEvent.change(screen.getByLabelText('可售净产量'), { target: { value: '24000' } })
    fireEvent.click(screen.getByRole('button', { name: '恢复已保存值' }))
    expect(screen.getByText('¥5.40')).toBeTruthy()
  })
  it('成熟预测保存后更新地块显示，不能把旧成熟期沿用到新作物', () => {
    setup(<ProductionPage/>, '/production?plot=SZT-001')
    fireEvent.click(screen.getByRole('button', { name: '成熟与产量设置' }))
    fireEvent.change(screen.getByLabelText('预计成熟日期'), { target: { value: '2026-09-10' } })
    fireEvent.click(screen.getByRole('button', { name: '保存演示预测' }))
    expect(screen.getByText('09-10')).toBeTruthy()
  })
  it('种植变更缺少视频时不能提交，两类材料齐全后进入待审', () => {
    setup(<ProductionPage/>, '/production?plot=SZT-001')
    fireEvent.click(screen.getByRole('button', { name: '申请种植变更' }))
    fireEvent.change(screen.getByLabelText('变更后的种植产品'), { target: { value: '夏黑葡萄' } })
    fireEvent.change(screen.getByLabelText('变更原因'), { target: { value: '试验地块更换新品种' } })
    const field = screen.getByLabelText('照片和视频（两类都必需）')
    const photo = new File(['photo'], 'photo.jpg', { type: 'image/jpeg' })
    fireEvent.change(field, { target: { files: [photo] } })
    fireEvent.click(screen.getByRole('button', { name: '提交变更申请' }))
    expect(screen.getByRole('alert').textContent).toContain('照片和视频')
    fireEvent.change(field, { target: { files: [photo, new File(['video'], 'video.mp4', { type: 'video/mp4' })] } })
    fireEvent.click(screen.getByRole('button', { name: '提交变更申请' }))
    expect(screen.getByText('待审核')).toBeTruthy()
    expect(screen.getByText('阳光玫瑰葡萄', { selector: '.farm-crop' })).toBeTruthy()
  })
  it('锁定2000斤转换为1000kg，出库后不重复扣减', () => {
    setup(<InventoryPage/>)
    fireEvent.click(within(screen.getByRole('row', { name: /BATCH-001/ })).getByRole('button', { name: '锁定采购' }))
    fireEvent.change(screen.getByLabelText('采购主体'), { target: { value: '测试加工车间' } })
    fireEvent.change(screen.getByLabelText('数量单位'), { target: { value: '斤' } })
    expect((screen.getByLabelText('锁定数量') as HTMLInputElement).value).toBe('2000')
    fireEvent.click(screen.getByRole('button', { name: '确认模拟锁定' }))
    const row = screen.getByRole('row', { name: /BATCH-001.*狮子头分拣/ })
    expect(within(row).getByText('500kg')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '确认模拟出库' }))
    expect(screen.queryByRole('button', { name: '确认模拟出库' })).toBeNull()
    expect(within(row).getByText('500kg')).toBeTruthy()
  })
  it('资源与成熟窗口筛选有空态，资源类型切换同步地图', () => {
    const view = setup(<ResourcesPage/>)
    fireEvent.change(screen.getByLabelText('资源类型'), { target: { value: '农机手' } })
    expect(screen.getByRole('button', { name: '查看陈师傅农机服务' })).toBeTruthy()
    fireEvent.change(screen.getByLabelText('搜索资源或所在地'), { target: { value: '不存在' } })
    expect(screen.getByText('没有匹配的资源')).toBeTruthy()
    view.unmount(); setup(<MaturityPage/>)
    fireEvent.change(screen.getByLabelText('成熟窗口'), { target: { value: '7' } })
    expect(screen.getByRole('button', { name: '查看阳光玫瑰葡萄' })).toBeTruthy()
    fireEvent.change(screen.getByLabelText('搜索地块、产品或所在地'), { target: { value: '不存在' } })
    expect(screen.getByText('没有匹配的地块')).toBeTruthy()
  })
  it('土壤核验归档与商家方案变更只执行本地状态流转', () => {
    const view = setup(<SoilPage/>)
    fireEvent.click(within(screen.getByRole('row', { name: /DEMO-S20260824/ })).getByRole('button', { name: '查看报告' }))
    fireEvent.click(screen.getByRole('button', { name: '模拟核验归档' }))
    expect(within(screen.getByRole('row', { name: /DEMO-S20260824/ })).getByText('已归档')).toBeTruthy()
    view.unmount(); setup(<MerchantsPage/>)
    fireEvent.click(within(screen.getByRole('row', { name: /BUY-002/ })).getByRole('button', { name: '配置服务方案' }))
    fireEvent.change(screen.getByLabelText('服务模式'), { target: { value: '年会员' } })
    fireEvent.click(screen.getByRole('button', { name: '保存演示方案' }))
    expect(within(screen.getByRole('row', { name: /BUY-002/ })).getByText('¥699.00 / 年')).toBeTruthy()
  })
  it('报送缺项阻断生成，导出标明内部资料格式', () => {
    setup(<TracePage/>)
    expect((screen.getByRole('button', { name: '生成本地预检任务' }) as HTMLButtonElement).disabled).toBe(true)
    expect(screen.getByText('尚有待核验农事记录')).toBeTruthy()
    expect(screen.getByText('无 / 未接入')).toBeTruthy()
    expect(screen.getByRole('button', { name: '导出内部资料JSON' })).toBeTruthy()
  })
  it('自营入库保留来源农户并展示金额，不产生付款', () => {
    setup(<ProcurementPage/>)
    fireEvent.click(screen.getByRole('button', { name: '新增收购入库' }))
    const dialog = within(screen.getByRole('dialog'))
    expect(dialog.getByText(/来源农户：林春梅/)).toBeTruthy()
    fireEvent.click(dialog.getByRole('button', { name: '登记模拟入库' }))
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(screen.getByRole('status').textContent).toContain('未执行付款')
  })
  it('缓存损坏和浏览器禁止写入时页面仍可用并告知用户', () => {
    localStorage.setItem('xiangqiao-admin-demo-actions-v1', '{broken')
    setup(<CardsPage/>)
    expect(screen.getByRole('alert').textContent).toContain('缓存不可用')
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('blocked') })
    fireEvent.click(within(screen.getByRole('row', { name: /XQ-C0001/ })).getByRole('button', { name: '模拟同步' }))
    expect(screen.getByRole('alert').textContent).toContain('当前会话有效')
  })
})
