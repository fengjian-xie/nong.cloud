// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { RootApp } from '../app/RootApp'
import CloudFarmSite from './CloudFarmSite'
import { filterPlots, isFarmPreviewPath, isFarmSiteHost } from './site'
import { demoStorageKey, loadDemoState, parseDemoState, saveDemoState, validAlias } from './storage'

beforeEach(() => { localStorage.clear(); vi.spyOn(window, 'scrollTo').mockImplementation(() => {}) })
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllEnvs() })
const renderFarm = (path = '/') => render(<MemoryRouter initialEntries={[path]}><CloudFarmSite/></MemoryRouter>)

describe('乡桥云农场独立演示', () => {
  it('消费者帮助入口提供本地问题登记，不显示坐席操作', () => {
    renderFarm('/help')
    expect(screen.getByRole('heading',{name:'遇到问题，乡桥帮你。'})).toBeTruthy()
    expect(screen.getByRole('link',{name:'帮助中心'}).getAttribute('href')).toBe('/help')
    expect(screen.queryByRole('button',{name:'演示受理与分派'})).toBeNull()
  })
  it('精确识别农场域名和预览路径，不接管其他站点', () => {
    expect(isFarmSiteHost('NC.NONG.CLOUD.')).toBe(true)
    for (const host of ['nong.cloud', 'y.nong.cloud', 'api.nong.cloud', 'm.nong.cloud', 'nc.nong.cloud.attacker.test']) expect(isFarmSiteHost(host)).toBe(false)
    expect(isFarmPreviewPath('/cloud-preview/plots/grape-a')).toBe(true)
    expect(isFarmPreviewPath('/cloud-previews')).toBe(false)
  })
  it('列表与摄像头过滤真实改变结果，不承诺真实直播', () => {
    renderFarm()
    expect(screen.getByRole('heading', { name: '看见田间，选择你的云农场。' })).toBeTruthy()
    expect(screen.getByText(/未接入真实地块/)).toBeTruthy()
    fireEvent.change(screen.getByLabelText('筛选镜头配置'), { target: { value: 'none' } })
    expect(screen.getByRole('heading', { name: '种植观察区（示例）' })).toBeTruthy()
    expect(screen.queryByRole('heading', { name: '葡萄园A区（示例）' })).toBeNull()
    fireEvent.change(screen.getByLabelText('搜索地块或作物'), { target: { value: '不存在' } })
    expect(screen.getByText('没有匹配的演示地块')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '清除筛选' }))
    expect(screen.getByText('3个场景示例')).toBeTruthy()
    expect(filterPlots(' B区 ', '', 'configured')).toHaveLength(1)
  })
  it('详情可切换照片、摄像头、档案，并保存关注', () => {
    renderFarm('/plots/grape-a')
    fireEvent.click(screen.getByRole('tab', { name: '摄像头' }))
    expect(screen.getByRole('heading', { name: '摄像头尚未接入' })).toBeTruthy()
    expect(document.querySelector('video')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: '查看产地影像' }))
    expect(screen.getByText('场景照片，非实时画面')).toBeTruthy()
    fireEvent.click(screen.getByRole('tab', { name: '地块档案' }))
    expect(screen.getByText('检测机构资料待接入')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '加入关注' }))
    expect(parseDemoState(localStorage.getItem(demoStorageKey)).favorites).toEqual(['grape-a'])
    fireEvent.click(screen.getByRole('button', { name: '已关注 · 取消关注' }))
    expect(parseDemoState(localStorage.getItem(demoStorageKey)).favorites).toEqual([])
  })
  it('必须知悉演示性质，不保存电话，只生成本地意向', () => {
    renderFarm('/plots/grape-a/apply')
    fireEvent.click(screen.getByRole('button', { name: '提交演示申请' }))
    expect(screen.getByRole('alert').textContent).toContain('请先确认')
    fireEvent.click(screen.getByRole('checkbox'))
    fireEvent.change(screen.getByLabelText('演示称呼'), { target: { value: '13800000000' } })
    fireEvent.click(screen.getByRole('button', { name: '提交演示申请' }))
    expect(screen.getByRole('alert').textContent).toContain('请勿输入手机号')
    fireEvent.change(screen.getByLabelText('演示称呼'), { target: { value: '演示访客' } })
    fireEvent.change(screen.getByLabelText('认购份数'), { target: { value: '2' } })
    fireEvent.click(screen.getByRole('button', { name: '提交演示申请' }))
    expect(screen.getByRole('heading', { name: '演示意向已保存' })).toBeTruthy()
    const state = parseDemoState(localStorage.getItem(demoStorageKey))
    expect(state.intents).toHaveLength(1)
    expect(state.intents[0].quantity).toBe(2)
    expect(screen.getByText(/不构成合同、不产生费用/)).toBeTruthy()
  })
  it('未公开地块与空列表有明确返回路径', () => {
    const view = renderFarm('/plots/private-id')
    expect(screen.getByRole('heading', { name: '没有找到这个地块' })).toBeTruthy()
    expect(screen.getByRole('link', { name: '返回农场列表' }).getAttribute('href')).toBe('/')
    view.unmount()
    renderFarm('/my-farm')
    expect(screen.getByRole('heading', { name: '还没有关注地块' })).toBeTruthy()
    fireEvent.click(screen.getByRole('tab', { name: '签约申请' }))
    expect(screen.getByRole('heading', { name: '还没有演示申请' })).toBeTruthy()
  })
  it('关注与申请可恢复、撤回，清空需二次确认', () => {
    saveDemoState({ version: 1, favorites: ['grape-a'], intents: [{ id: 'demo-1', plotId: 'grape-a', alias: '演示访客', quantity: 1, delivery: '待协商', createdAt: new Date().toISOString() }] })
    renderFarm('/my-farm?tab=applications')
    expect(screen.getByText('已保存（演示）')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '撤回演示申请' }))
    expect(screen.getByRole('heading', { name: '还没有演示申请' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '清空本设备演示数据' }))
    expect(loadDemoState().state.favorites).toEqual(['grape-a'])
    fireEvent.click(screen.getByRole('button', { name: '确认清空' }))
    expect(loadDemoState().state.favorites).toEqual([])
  })
  it('版本、字段、无效资料和异常储存均安全处理', () => {
    expect(parseDemoState('{broken').favorites).toEqual([])
    expect(parseDemoState(JSON.stringify({ version: 9, favorites: ['grape-a'], intents: [] })).favorites).toEqual([])
    const state = parseDemoState(JSON.stringify({ version: 1, favorites: ['grape-a', 'grape-a', 'secret'], intents: [null, { id: 'demo', plotId: 'grape-a', alias: '访客', quantity: 2, delivery: '待协商', createdAt: '2026-10-04T00:00:00Z', token: 'must-not-keep' }] }))
    expect(state.favorites).toEqual(['grape-a'])
    expect(state.intents[0]).not.toHaveProperty('token')
    expect(validAlias('a@example.com')).toBe(false)
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('blocked') })
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('blocked') })
    expect(loadDemoState().available).toBe(false)
    expect(saveDemoState(state)).toBe(false)
    renderFarm()
    expect(screen.getByRole('status').textContent).toContain('储存不可用')
  })
  it('独立模式渲染农场，API站点优先不被覆盖', async () => {
    vi.stubEnv('MODE', 'farm-site')
    const view = render(<MemoryRouter><RootApp hostname="nc.nong.cloud"/></MemoryRouter>)
    expect(await screen.findByRole('heading', { name: '看见田间，选择你的云农场。' })).toBeTruthy()
    view.unmount()
    render(<MemoryRouter><RootApp hostname="api.nong.cloud"/></MemoryRouter>)
    expect(await screen.findByRole('heading', { name: 'API开放平台' })).toBeTruthy()
    expect(screen.queryByRole('heading', { name: '看见田间，选择你的云农场。' })).toBeNull()
  })
})
